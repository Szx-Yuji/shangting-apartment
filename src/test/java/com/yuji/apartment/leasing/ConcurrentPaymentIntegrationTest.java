package com.yuji.apartment.leasing;

import org.junit.jupiter.api.Test;
import org.springframework.context.annotation.AnnotationConfigApplicationContext;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.jdbc.datasource.AbstractDataSource;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import org.springframework.transaction.support.TransactionSynchronizationManager;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.SQLException;
import java.time.LocalDate;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

import static org.junit.jupiter.api.Assertions.*;

/** Two actual JDBC transactions start with a repeatable-read connection default. */
class ConcurrentPaymentIntegrationTest {
    @Configuration(proxyBeanMethods=false)
    @EnableTransactionManagement
    static class TransactionConfiguration {}

    static final class RepeatableReadDataSource extends AbstractDataSource {
        private final DataSource delegate;
        RepeatableReadDataSource(DataSource delegate) { this.delegate=delegate; }
        @Override public Connection getConnection() throws SQLException {
            Connection connection=delegate.getConnection();
            connection.setTransactionIsolation(Connection.TRANSACTION_REPEATABLE_READ);
            return connection;
        }
        @Override public Connection getConnection(String username,String password) throws SQLException {
            return getConnection();
        }
    }

    static final class ConcurrentRepository extends LeasingRepository {
        final CountDownLatch firstReads=new CountDownLatch(2);
        final List<Integer> observedIsolation=new CopyOnWriteArrayList<>();
        ConcurrentRepository(JdbcClient jdbc) { super(jdbc); }
        @Override public Optional<BillData> findBill(long id) {
            Optional<BillData> result=super.findBill(id);
            observedIsolation.add(TransactionSynchronizationManager.getCurrentTransactionIsolationLevel());
            firstReads.countDown();
            try {
                if (!firstReads.await(5,TimeUnit.SECONDS)) throw new AssertionError("initial reads did not overlap");
            } catch (InterruptedException exception) {
                Thread.currentThread().interrupt();
                throw new AssertionError(exception);
            }
            return result;
        }
    }

    @Test
    void simultaneousIdempotentPaymentsReturnPaidStatusAndTimestamp() throws Exception {
        String name="leasing_payment_"+UUID.randomUUID().toString().replace("-","");
        var raw=new DriverManagerDataSource("jdbc:h2:mem:"+name+";MODE=MySQL;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=5000","sa","");
        var source=new RepeatableReadDataSource(raw);
        JdbcClient jdbc=JdbcClient.create(source);
        jdbc.sql("CREATE TABLE apartment(id BIGINT PRIMARY KEY,name VARCHAR(100))").update();
        jdbc.sql("CREATE TABLE room(id BIGINT PRIMARY KEY,apartment_id BIGINT,room_number VARCHAR(20))").update();
        jdbc.sql("""
                CREATE TABLE lease_contract(id BIGINT PRIMARY KEY,room_id BIGINT,user_id BIGINT,
                start_date DATE,end_date DATE,monthly_rent DECIMAL(10,2),deposit DECIMAL(10,2),status VARCHAR(20))
                """).update();
        jdbc.sql("""
                CREATE TABLE bill(id BIGINT PRIMARY KEY,lease_id BIGINT,user_id BIGINT,period VARCHAR(7),
                due_date DATE,amount DECIMAL(10,2),status VARCHAR(20),paid_at TIMESTAMP,
                payment_channel VARCHAR(20),created_at TIMESTAMP)
                """).update();
        jdbc.sql("""
                CREATE TABLE notification(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT,title VARCHAR(100),content VARCHAR(500),is_read BOOLEAN,created_at TIMESTAMP)
                """).update();
        jdbc.sql("INSERT INTO apartment VALUES(1,'并发测试公寓')").update();
        jdbc.sql("INSERT INTO room VALUES(3,1,'301')").update();
        jdbc.sql("INSERT INTO lease_contract VALUES(7,3,42,?,?,2500,2500,'ACTIVE')")
                .params(LocalDate.of(2026,1,1),LocalDate.of(2027,1,1)).update();
        jdbc.sql("INSERT INTO bill VALUES(9,7,42,'2026-01',?,5000,'UNPAID',NULL,NULL,CURRENT_TIMESTAMP)")
                .param(LocalDate.of(2026,1,1)).update();

        ConcurrentRepository repository=new ConcurrentRepository(jdbc);
        try (var context=new AnnotationConfigApplicationContext()) {
            context.register(TransactionConfiguration.class);
            context.registerBean("transactionManager",DataSourceTransactionManager.class,
                    ()->new DataSourceTransactionManager(source));
            context.registerBean(LeasingService.class,()->new LeasingService(repository,true));
            context.refresh();
            LeasingService service=context.getBean(LeasingService.class);
            try (var executor=Executors.newFixedThreadPool(2)) {
                var first=executor.submit(()->service.pay(9,42L,true));
                var second=executor.submit(()->service.pay(9,42L,true));
                var one=first.get(10,TimeUnit.SECONDS);
                var two=second.get(10,TimeUnit.SECONDS);
                assertEquals("PAID",one.status());
                assertEquals("PAID",two.status());
                assertNotNull(one.paidAt());
                assertNotNull(two.paidAt());
                assertEquals(one.paidAt(),two.paidAt());
            }
            assertEquals(List.of(Connection.TRANSACTION_READ_COMMITTED,Connection.TRANSACTION_READ_COMMITTED),
                    repository.observedIsolation);
            assertEquals(1L,jdbc.sql("SELECT COUNT(*) FROM notification").query(Long.class).single());
            assertEquals(1L,jdbc.sql("SELECT COUNT(*) FROM bill WHERE status='PAID'").query(Long.class).single());
        } finally {
            jdbc.sql("SHUTDOWN").update();
        }
    }
}
